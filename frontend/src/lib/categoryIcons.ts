export const CATEGORY_ICONS: IconChoice[] = LIST.map(([name, Icon, words]) => ({ name, Icon, words }));

const BY_NAME = new globalThis.Map(CATEGORY_ICONS.map((c) => [c.name, c.Icon]));

/** The icon for a stored name; a plain tag for names this version does not know. */
export function iconFor(name: string): LucideIcon {
  return BY_NAME.get(name) ?? Tag;
}

/** Icons where every typed word starts one of the icon's words ("pet", "gym", "rent"),
 *  so "pet" finds pets but not "petrol". */
export function searchIcons(query: string): IconChoice[] {
  const typed = query.toLowerCase().split(/\s+/).filter(Boolean);
  if (typed.length === 0) return CATEGORY_ICONS;
  return CATEGORY_ICONS.filter((c) => {
    const words = `${c.name.replaceAll("-", " ")} ${c.words}`.split(" ");
    return typed.every((t) => words.some((w) => w.startsWith(t)));
  });
}
